"""Поиск RSS по сайту: правила вместо догадки.

Человек называет сайт — домен или адрес, — программа сама находит ленту и
подключает её как источник. Просить может любой приглашённый: каталог общий,
а выбор из него — личный. Модели здесь нет, и это осознанный выбор: два
детерминированных правила закрывают почти все сайты, а «знание по памяти»,
которое предложила бы модель, устаревает быстрее, чем сайты меняют ленты —
домен Бумаги уже продавался однажды, и по памяти туда пришёл бы сайт про
микрозаймы [DOC-003].

1. Автодискавери: `<link rel="alternate" type="application/rss+xml">` в
   разметке главной страницы. Так ленту объявляют WordPress и почти все
   современные сайты. Ссылки с «rss», «feed» или «atom» в адресе идут
   следом: в подвале сайт часто пишет просто «RSS», без `<link>`.
2. Стандартные пути: `/feed/`, `/rss/`, `/rss.xml` и ещё несколько. Так
   лента находится там, где её забыли объявить.

Каждый кандидат проверяется программой, а не принимается на веру: в ленте
должно быть минимум три записи с настоящими адресами, и лежать она должна
на том же домене или его поддомене — чужой агрегатор под видом издания
собирал бы нам чужие материалы и врал про источник [CORE-016]. Адрес,
разрешающийся в частную сеть, не проверяется вовсе: поле ввода открыто
человеку, а HTTP-клиент ходит от имени нашего сервера [CORE-016].

Найденная лента входит в сбор сразу: сторож для неё создаётся здесь же, с
интервалом по замеру двери — честный `Last-Modified` это 10 секунд,
тяжёлая лента без валидаторов 30 [NEWS-005]. Первый заход — холодный старт:
всё, что лежало в ленте до подключения, записывается в архив, но не
рассылается [NEWS-001].

Веб и бот только оставляют просьбу: страница обязана отвечать сразу, а не
держать соединение, пока мы ходим по чужим адресам [NEWS-002]. Результат
уходит сообщением тому, кто просил, и владельцу — как и уведомления о
входах, это дешевле любой системы наблюдения [NEWS-007].
"""

from __future__ import annotations

import asyncio
import html
import logging
import re
import sqlite3
import urllib.parse
from typing import Any
from xml.etree import ElementTree

from . import access, fetch, sources, store, watch

log = logging.getLogger("fpnews.discover")

# Пути, по которым лента живёт чаще всего. Проверяются после объявленных на
# странице: угаданная по пути лента — второй сорт. Со слэшем и без: «rss» у
# Ленты и «rss/» у Вести — оба живые, и это одинаковые случаи.
СТАНДАРТНЫЕ_ПУТИ = ("feed/", "rss/", "rss", "feed", "rss.xml", "feed.xml",
                    "atom.xml", "index.xml")
# Сколько кандидатов проверяем. Объявленную на странице ленту обычно видно
# сразу; глубже восьми заходов значит, что ленты для нас нет.
МАКСИМУМ_КАНДИДАТОВ = 8
# Меньше трёх записей — это не лента, а заглушка: одна-две ссылки могли
# остаться от заброшенного раздела.
МИНИМУМ_ЗАПИСЕЙ = 3
# Потолок очереди просьб. Без него поле ввода превращается в «позови сервер
# куда хочет любой желающий» [CORE-016].
ОЧЕРЕДЬ = 5
# Лента тяжелее этого без валидаторов опрашивается редко: трафик дороже
# новизны [NEWS-004].
ТЯЖЁЛАЯ = 300_000

LINK = re.compile(r"<link\b[^>]*>", re.I)
HREF = re.compile(r"href=[\"']([^\"']+)[\"']", re.I)
TYPE = re.compile(r"type=[\"']([^\"']+)[\"']", re.I)
ПОХОЖАЯ = re.compile(r"feed|rss|atom", re.I)

# Просьбы из веба и бота: (сайт, кто просил).
ЗАДАНИЯ: list[tuple[str, int]] = []
# Последние результаты поиска — страница «Источники» показывает их, чтобы
# человек видел, чем кончился поиск, не открывая журнал.
СВОДКА: list[str] = []
# Сторожа добавленных лент. Останавливаются выборочно, при удалении.
_сторожа: dict[str, tuple[Any, asyncio.Event]] = {}


def нормализовать(что: Any) -> str:
    """Адрес сайта из ответа человека. Пусто — это не сайт.

    Домен без схемы дополняем до https. Слово без точки сайтом не считаем:
    детерминированные правила не умеют превращать «Коммерсантъ» в адрес, и
    выдумывать его — работа модели, а не парсера. Пробел внутри адреса —
    тоже не адрес, каким бы невинным он ни выглядел [CORE-016].
    """
    текст = str(что or "").strip()
    if not текст or len(текст) > 200 or " " in текст:
        return ""
    if not текст.lower().startswith(("http://", "https://")):
        if "." not in текст or текст.startswith("."):
            return ""
        текст = "https://" + текст
    части = urllib.parse.urlsplit(текст)
    if части.scheme not in ("http", "https") or not части.netloc:
        return ""
    return urllib.parse.urlunsplit(
        (части.scheme, части.netloc, части.path or "/", "", ""))


def хост(адрес: str) -> str:
    """Имя хоста: нижним регистром, без порта и «www.»."""
    raw = urllib.parse.urlsplit(str(адрес or "")).netloc.split("@")[-1]
    имя = raw.split(":")[0].strip().lower()
    return имя[4:] if имя.startswith("www.") else имя


async def наружный(адрес: str) -> bool:
    """Хост общедоступен: не localhost и не частная сеть.

    DNS-ответ — тоже данные снаружи: проверяем каждый адрес, на который имя
    разрешается, а не только первый [CORE-016].
    """
    import ipaddress  # noqa: PLC0415
    import socket  # noqa: PLC0415

    части = urllib.parse.urlsplit(адрес)
    имя = (части.hostname or "").strip().lower()
    if not имя or имя == "localhost" or имя.endswith((".local", ".internal", ".lan")):
        return False
    if части.port not in (None, 80, 443):
        return False
    try:
        ответы = await asyncio.get_running_loop().getaddrinfo(имя, части.port or 443)
    except (socket.gaierror, UnicodeError, OSError):
        return False
    for ответ in ответы:
        try:
            ip = ipaddress.ip_address(ответ[4][0])
        except ValueError:
            return False
        if (ip.is_private or ip.is_loopback or ip.is_link_local
                or ip.is_reserved or ip.is_multicast):
            return False
    return True


async def _опрос(session: Any, адрес: str) -> tuple[Any, Any]:
    """Опрос с одним вежливым повтором внутри того же домена.

    Домен без «www» часто просит «идите на www»: строгий `poll` отвечает
    отказом, и для сторожа это правильно. Для разового поиска — нет: мы сами
    попросили человека назвать сайт, и «www.» — это тот же сайт. Повторяем
    один раз и только на тот же домен; чужие адреса остаются чужими.
    """
    дверь = fetch.Door()
    poll = await fetch.poll(session, адрес, дверь)
    if (poll.url and poll.error.startswith("дверь увела")
            and тот_же_домен(poll.url, адрес)):
        дверь = fetch.Door()
        poll = await fetch.poll(session, poll.url, дверь)
    return poll, дверь


def тот_же_домен(лента: str, сайт: str) -> bool:
    """Лента лежит на сайте или его поддомене, а не у чужого агрегатора."""
    где = хост(лента)
    чей = хост(сайт)
    if not где or not чей:
        return False
    return где == чей or где.endswith("." + чей)


def из_главной(тело: str, host: str) -> list[str]:
    """Кандидаты, объявленные на самой странице.

    Сначала честное автодискавери из `<head>`, затем ссылки с «feed», «rss»
    или «atom» в адресе. Порядок сохраняем: объявленная лента надёжнее
    найденной по слову.
    """
    найдено: list[str] = []
    for тег in LINK.findall(тело or ""):
        тип = TYPE.search(тег)
        if тип is None or not re.search(r"rss|atom", тип.group(1).lower()):
            continue
        href = HREF.search(тег)
        if href is None:
            continue
        адрес = sources.canonical(href.group(1), "https://" + host)
        if адрес and адрес not in найдено:
            найдено.append(адрес)
    for href, _ in sources.ANCHOR.findall(тело or ""):
        if not ПОХОЖАЯ.search(href or ""):
            continue
        адрес = sources.canonical(href, "https://" + host)
        if адрес and адрес not in найдено:
            найдено.append(адрес)
    return найдено[:МАКСИМУМ_КАНДИДАТОВ]


def кандидаты(адрес: str, тело_главной: str = "") -> list[str]:
    """Порядок проверки: объявленные на странице, затем стандартные пути."""
    host = хост(адрес)
    часть = urllib.parse.urlsplit(адрес)
    out: list[str] = []
    if (часть.path or "/") not in ("", "/"):
        # Указан не домен, а конкретный путь — возможно, сама лента. Считаем
        # его кандидатом первым и на главную не ходим.
        out.append(адрес)
    if тело_главной:
        out += [адрес for адрес in из_главной(тело_главной, host) if адрес not in out]
    if (часть.path or "/") in ("", "/"):
        for путь in СТАНДАРТНЫЕ_ПУТИ:
            вариант = urllib.parse.urlunsplit(
                (часть.scheme, часть.netloc, "/" + путь, "", ""))
            if вариант not in out:
                out.append(вариант)
    return out[:МАКСИМУМ_КАНДИДАТОВ]


def название_ленты(тело: str) -> str:
    """Название издания из самой ленты. Пусто — возьмётся из домена."""
    try:
        корень = ElementTree.fromstring(тело or "")
    except ElementTree.ParseError:
        return ""
    for элемент in корень.iter():
        if str(элемент.tag or "").rsplit("}", 1)[-1] == "title":
            return sources.text_of(элемент.text or "")[:80]
    return ""


async def найти(session: Any, сайт: str) -> dict[str, Any]:
    """Лента по сайту. `ошибка` — словами, остальное — данными для записи."""
    адрес = нормализовать(сайт)
    if not адрес:
        return {"ошибка": "укажите домен или адрес сайта, например example.com"}
    if not await наружный(адрес):
        return {"ошибка": "этот адрес ведёт не в интернет, а в локальную сеть "
                          "или закрытый порт — проверять его мы не станем"}
    тело_главной = ""
    if (urllib.parse.urlsplit(адрес).path or "/") in ("", "/"):
        опрос, _ = await _опрос(session, адрес)
        if опрос.error and not опрос.body:
            return {"ошибка": "сайт не ответил: {}".format(опрос.error)}
        тело_главной = опрос.body
    проверено = 0
    for кандидат in кандидаты(адрес, тело_главной):
        if not тот_же_домен(кандидат, адрес) or проверено >= МАКСИМУМ_КАНДИДАТОВ:
            continue
        проверено += 1
        опрос, дверь = await _опрос(session, кандидат)
        if not опрос.body:
            continue
        проба = sources.Source(code="проба", label="проба", door=кандидат, kind="rss",
                               interval=15.0, conditional=False, host="https://" + хост(кандидат))
        найдено = sources.extract(проба, опрос.body)
        if len(найдено) < МИНИМУМ_ЗАПИСЕЙ:
            continue
        валидаторы = bool(дверь.etag or дверь.modified)
        интервал = 10.0 if валидаторы else (30.0 if опрос.size > ТЯЖЁЛАЯ else 15.0)
        return {
            "лента": кандидат,
            "название": название_ленты(опрос.body) or хост(кандидат),
            "host": хост(кандидат),
            "интервал": интервал,
            "условный": валидаторы,
            "размер": опрос.size,
            "секунд": round(опрос.seconds, 2),
            "записей": len(найдено),
        }
    return {"ошибка": "ленты на {} не нашлось — попробуйте указать её адрес "
                      "целиком".format(хост(адрес))}


def попросить(сайт: str, кто: int = 0) -> bool:
    """Положить просьбу в очередь. Дубль и переполнение — вежливый отказ."""
    сайт = str(сайт or "").strip()
    if not сайт or len(ЗАДАНИЯ) >= ОЧЕРЕДЬ:
        return False
    if any(уже == сайт for уже, _ in ЗАДАНИЯ):
        return False
    ЗАДАНИЯ.append((сайт, int(кто or 0)))
    return True


def погасить(code: str) -> None:
    """Остановить сторожа убранной ленты. Не работал — ничего и не делаем."""
    пара = _сторожа.pop(str(code or ""), None)
    if пара is not None:
        пара[1].set()


def сводка() -> list[str]:
    """Последние результаты поиска — для страницы «Источники»."""
    return list(СВОДКА)


def _запомнить(строка: str) -> None:
    СВОДКА.insert(0, строка)
    del СВОДКА[5:]


async def _сказать(bot: Any, кому: list[int], текст: str) -> None:
    """Сообщение о результате. Бота нет — журнал скажет за нас."""
    log.info("поиск ленты: %s", текст)
    if bot is None or not getattr(bot, "ready", False):
        return
    for номер in кому:
        try:
            await bot.send(int(номер), текст, preview=False)
        except Exception:  # noqa: BLE001 — сообщение не роняет сбор [CORE-017]
            pass


def _заголовок(строка: str) -> str:
    """Название ленты для сообщения: оно из чужого ответа, экранируем [CORE-016]."""
    return html.escape(str(строка or "").strip() or "лента")


async def loop(bot: Any, session: Any, conn: sqlite3.Connection, stop: asyncio.Event,
               queue: "asyncio.Queue[int] | None" = None) -> int:
    """Контур поиска: берёт просьбу, ходит в сеть, подключает ленту.

    Отдельная задача, а не часть обработчика страницы: поиск занимает
    секунды на чужом сайте, и страница не имеет права столько молчать
    [NEWS-002].
    """
    обработано = 0
    try:
        while not stop.is_set():
            if not ЗАДАНИЯ:
                try:
                    await asyncio.wait_for(stop.wait(), timeout=1.0)
                except asyncio.TimeoutError:
                    pass
                continue
            сайт, кто = ЗАДАНИЯ.pop(0)
            обработано += 1
            итог = await найти(session, сайт)
            кому: list[int] = []
            for номер in (кто, *access.владельцы(conn)):
                if номер and номер not in кому:
                    кому.append(номер)
            if "ошибка" in итог:
                строка = "{}: {}".format(сайт, итог["ошибка"])
                _запомнить(строка)
                await _сказать(bot, кому, "Лента {}: {}".format(сайт, итог["ошибка"]))
                continue
            дубль = None
            for источник in sources.registry(conn).values():
                if хост(источник.door) == итог["host"]:
                    дубль = источник
                    break
            if дубль is not None:
                строка = "{}: этот сайт уже подключён — {}".format(сайт, дубль.label)
                _запомнить(строка)
                await _сказать(bot, кому, "Лента " + строка)
                continue
            code = store.add_feed(conn, label=итог["название"], door=итог["лента"],
                                   kind="rss", interval=итог["интервал"],
                                   conditional=итог["условный"], host=итог["host"],
                                   added_by=кто)
            from . import deliver  # noqa: PLC0415 — импорт здесь разрывает круг

            deliver.LABEL[code] = итог["название"]
            источник = sources.registry(conn)[code]
            стопчик = asyncio.Event()
            задача = asyncio.create_task(
                watch.loop(session, источник, conn, стопчик, queue),
                name="сторож-{}".format(code))
            _сторожа[code] = (задача, стопчик)
            строка = ("Подключено издание «{name}» — записей {записей}, интервал "
                      "{интервал} с, {килобайт} КБ за {секунд} с.\n{лента}").format(
                name=_заголовок(итог["название"]), записей=итог["записей"],
                интервал=int(итог["интервал"]),
                килобайт=max(1, итог["размер"] // 1024), секунд=итог["секунд"],
                лента=html.escape(итог["лента"]))
            _запомнить("{}: подключено «{}»".format(сайт, _заголовок(итог["название"])))
            await _сказать(bot, кому, строка)
    finally:
        # Свои сторожа останавливаем сами: глобальный стоп их не касается,
        # а процесс не должен ждать сторожа, которого уже никто не читает.
        for _, (_, стопчик) in _сторожа.items():
            стопчик.set()
        if _сторожа:
            await asyncio.gather(*[пара[0] for пара in _сторожа.values()],
                                 return_exceptions=True)
    return обработано


