"""Сравнение редакций: убранная формулировка должна быть видна.

Проверяется главное обещание шага 10: диф показывает, что именно исчезло из
материала, считает правку в словах и знаках и не даёт чужому HTML попасть на
страницу.
"""

from __future__ import annotations

from news import diff


def test_убранное_и_дописанное_размечаются() -> None:
    было = "Подозреваемый задержан вчера вечером"
    стало = "Подозреваемый доставлен для беседы вчера вечером"
    разметка = diff.markup(было, стало)
    assert "<del>задержан " in разметка
    assert "<ins>доставлен для беседы " in разметка
    assert "Подозреваемый" in разметка and разметка.count("Подозреваемый") == 1


def test_исчезнувший_абзац_виден_целиком() -> None:
    было = "Первый абзац. Работы получила компания подрядчика. Третий абзац."
    стало = "Первый абзац. Третий абзац."
    части = dict((вид, текст) for вид, текст in diff.parts(было, стало))
    assert "Работы получила компания подрядчика." in части["убрано"]
    assert "добавлено" not in части


def test_чужой_html_экранируется() -> None:
    разметка = diff.markup("текст", '<script>alert(1)</script>')
    assert "<script>" not in разметка
    assert "&lt;script&gt;" in разметка


def test_сводка_считает_слова_и_знаки() -> None:
    сводка = diff.summary("раз два три четыре", "раз два пять")
    assert сводка["убрано_слов"] == 2 and сводка["добавлено_слов"] == 1
    assert сводка["знаков"] == len("раз два пять") - len("раз два три четыре")
    assert сводка["менялось"]


def test_без_изменений_так_и_говорит() -> None:
    assert diff.phrase("один и тот же текст", "один и тот же текст") == "без изменений"
    assert not diff.summary("текст", "текст")["менялось"]


def test_длинный_текст_режется_потолком() -> None:
    длинный = "слово " * 40_000
    assert len(длинный) > diff.MAX_CHARS
    assert diff.markup(длинный, длинный + "хвост")  # не зависает и не падает
