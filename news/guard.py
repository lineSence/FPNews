"""Охрана веба: кому что можно, какие заголовки уходят, что мы подчищаем.

Вынесено из `news/web.py` по двум причинам. Первая — размер: маршрутизация
и решения о доступе вместе уже не помещались в тридцать килобайт `[CORE-024]`.
Вторая важнее: «кому можно» должно лежать в одном месте. Пока проверка роли
была размазана по маршрутам, её просто не написали ни разу — и любой
приглашённый читатель мог выключить источник, запустить `VACUUM` и разбудить
сторожей `[CORE-016]`.

Три вещи, которые здесь решаются.

1. **Роли.** Читатель наблюдает, владелец распоряжается. Список
   владельческих форм закрыт и лежит рядом с объяснением, а не в `if`-ах.
2. **Заголовки ответа.** Ни одной строчки JavaScript у нас нет, поэтому
   политика содержимого самая узкая из возможных, а значения заголовков
   чистятся от управляющих символов: `Location` мы собираем из того, что
   пришло в запросе.
3. **Уборка.** Просроченные сессии и несгоревшие коды входа не удалял никто.
   Место здесь не главное — главное, что мёртвая строка не должна лежать
   рядом с живыми и переживать отзыв приглашения.
"""

from __future__ import annotations

import logging
import os
import time
from typing import Any

from . import access

log = logging.getLogger("fpnews.guard")

# Политика содержимого. У нас нет ни скриптов, ни картинок со стороны, ни
# шрифтов: страницы — это разметка и один встроенный `<style>`. Значит всё
# запрещено, кроме встроенного стиля и отправки форм на свой же адрес.
# `frame-ancestors 'none'` закрывает обрамление чужой страницей, `base-uri
# 'none'` — подмену основы для относительных ссылок [CORE-016].
CSP = ("default-src 'none'; style-src 'unsafe-inline'; form-action 'self'; "
       "base-uri 'none'; frame-ancestors 'none'")
# Год — минимум, который браузеры считают осмысленным. Заголовок уходит
# только когда снаружи действительно HTTPS: на `http://127.0.0.1` он закрыл
# бы интерфейс до всякого сертификата.
HSTS = "max-age=31536000; includeSubDomains"
# `no-store`, потому что каждая страница персональна: в ней темы, запросы и
# приглашения. Чужая копия в кэше прокси нам не нужна.
ЗАЩИТА = (
    ("X-Content-Type-Options", "nosniff"),
    ("Referrer-Policy", "same-origin"),
    ("Content-Security-Policy", CSP),
    ("X-Frame-Options", "DENY"),
    ("Cache-Control", "no-store"),
)

# Формы, которые меняют не своё, а общее: настройку сбора, файл базы, список
# людей. Своё — темы, запросы, отдачу в Telegram — читатель меняет сам.
ФОРМЫ_ВЛАДЕЛЬЦА = frozenset({
    "/источники/переключить",
    "/источники/интервал",
    "/источники/добавить",
    "/источники/удалить",
    "/хранение/копии",
    "/хранение/сжать",
    "/опросить",
    "/проверка",
    "/доступы/выдать",
    "/доступы/отозвать",
})
# Страницы, где видно чужие приглашения. Лента, поиск и архив сюда не входят
# намеренно: читателя позвали именно наблюдать, и те же строки он видит на
# страницах — запрет на выгрузку не защитил бы ничего [NEWS-007].
СТРАНИЦЫ_ВЛАДЕЛЬЦА = frozenset({"/доступы"})

ОТКАЗ = ("Это может только владелец. Вы вошли как читатель: смотреть можно всё, "
         "а менять сбор, чистить базу и выдавать доступы — нет.")

# Попытки входа по коду. Считаем на весь процесс: до входа мы не знаем, кто
# стучится, и ключа для счётчика у нас нет. Ограничитель не заменяет длину
# кода — двенадцать случайных знаков перебором не берутся; он бережёт журнал
# и процессор от шума и делает перебор видимым [NEWS-002].
ПОПЫТОК_ВХОДА = 30
ОКНО_ВХОДА = 600.0
_входы: list[float] = []


def за_проксёй() -> bool:
    """Снаружи HTTPS. Только тогда уместны HSTS и «Secure» в куке."""
    return (os.getenv("FPNEWS_WEB_SECURE") or "") == "1"


def заголовки() -> list[str]:
    """Строки защитных заголовков для любого ответа."""
    out = ["{}: {}".format(имя, значение) for имя, значение in ЗАЩИТА]
    if за_проксёй():
        out.append("Strict-Transport-Security: {}".format(HSTS))
    return out


def чисто(value: Any) -> str:
    """Значение заголовка без управляющих символов.

    `Location` и `Set-Cookie` собираются из того, что пришло в запросе: адрес
    возврата после смены темы, имя файла выгрузки. Перевод строки внутри
    такого значения разрезает ответ, и дальше можно дописать свои заголовки
    и своё тело — это склейка ответов `[CORE-016]`. Проверять надо после
    разбора: `parse_qsl` раскодирует `%0d%0a` сам, и до этой строки символ
    доезжает настоящим.
    """
    return "".join(знак for знак in str(value or "")
                   if ord(знак) >= 32 and ord(знак) != 127)


def владельцу_ли(path: str, method: str = "GET") -> bool:
    """Нужна ли роль владельца для этого адреса."""
    список = ФОРМЫ_ВЛАДЕЛЬЦА if str(method).upper() == "POST" else СТРАНИЦЫ_ВЛАДЕЛЬЦА
    return str(path) in список


def пускать(conn: Any, user_id: Any, path: str, method: str = "GET") -> bool:
    """Можно ли этому человеку сюда. Отказ пишем в журнал с адресом."""
    if not владельцу_ли(path, method):
        return True
    можно = access.владелец(conn, user_id)
    if not можно:
        log.warning("отказ: %s %s без роли владельца (человек %s)",
                    str(method).upper(), path, user_id)
    return можно


def отозван(conn: Any, user_id: Any) -> bool:
    """Роль снята, а кука в браузере ещё жива.

    `access.отозвать` гасит сессии, но человека можно лишить роли и руками,
    да и кука живёт тридцать дней. Отдельная проверка дешевле, чем надежда
    на то, что все пути отзыва вспомнят про сессии.
    """
    row = conn.execute("SELECT role FROM users WHERE id = ?",
                       (int(user_id or 0),)).fetchone()
    return row is not None and str(row["role"] or "") not in access.РОЛИ


def убрать_просроченное(conn: Any) -> int:
    """Выбросить мёртвые сессии и несгоревшие коды входа."""
    убрано = conn.execute(
        "DELETE FROM sessions WHERE expires_at <= datetime('now')").rowcount or 0
    убрано += conn.execute(
        "DELETE FROM login_codes WHERE expires_at <= datetime('now')").rowcount or 0
    conn.commit()
    return max(int(убрано), 0)


def неудачный_вход() -> int:
    """Запомнить неудачу и сказать, сколько их накопилось в окне."""
    сейчас = time.monotonic()
    _входы[:] = [шаг for шаг in _входы if сейчас - шаг < ОКНО_ВХОДА]
    _входы.append(сейчас)
    return len(_входы)


def много_попыток() -> bool:
    """Пора отвечать «слишком часто» вместо страницы входа."""
    сейчас = time.monotonic()
    _входы[:] = [шаг for шаг in _входы if сейчас - шаг < ОКНО_ВХОДА]
    return len(_входы) >= ПОПЫТОК_ВХОДА


def забыть_входы() -> None:
    """Сброс счётчика: после удачного входа и в тестах."""
    _входы.clear()


__all__ = ("CSP", "HSTS", "ОКНО_ВХОДА", "ОТКАЗ", "ПОПЫТОК_ВХОДА", "СТРАНИЦЫ_ВЛАДЕЛЬЦА",
           "ФОРМЫ_ВЛАДЕЛЬЦА", "ЗАЩИТА", "владельцу_ли", "заголовки", "забыть_входы",
           "за_проксёй", "много_попыток", "неудачный_вход", "отозван", "пускать",
           "убрать_просроченное", "чисто")
