"""Мост между вебом и сторожами: кнопка на странице будит опрос.

Зачем он нужен. Сторожа и веб живут в одном процессе и на одном событийном
цикле, но не знают друг о друге: сторож не должен ничего знать про страницы
`[NEWS-002]`. Чтобы кнопка «Опросить сейчас» работала, нужен один маленький
общий стол, куда веб кладёт просьбу, а сторож её забирает.

Почему не очередь в базе. Просьба живёт секунды и не переживает перезапуск —
записывать её на диск незачем `[CORE-025]`. Модуль хранит состояние в памяти
процесса, и это сознательное ограничение: если веб запущен отдельно от
сторожей (`python -m news.web`), журнал заходов пуст, и страница честно
говорит «сторожа в этом процессе не работают», а не рисует нули `[NEWS-001]`.
"""

from __future__ import annotations

import asyncio
import time
from typing import Any

# Кто сейчас слушает просьбы: код издания → событие его сторожа.
_СТОРОЖА: dict[str, asyncio.Event] = {}
# Последний заход по каждому изданию: что видели своими глазами.
ЖУРНАЛ: dict[str, dict[str, Any]] = {}
# Кто прямо сейчас стоит у двери.
_В_ДВЕРЯХ: set[str] = set()
# Кому отправить проверочное сообщение в бот. Складываем номера, а не тексты.
ТЕСТЫ: list[int] = []
# Итог последней проверки связи: время и ответ. Пусто — ещё не проверяли.
ПРОВЕРКА: dict[str, Any] = {}
# Когда процесс начал работу и когда последний раз просили опросить.
НАЧАЛО = time.time()
ПРОСИЛИ: float | None = None


def подписаться(code: str) -> asyncio.Event:
    """Сторож заявляет о себе и получает своё событие пробуждения."""
    событие = asyncio.Event()
    _СТОРОЖА[code] = событие
    return событие


def отписаться(code: str) -> None:
    """Сторож ушёл: больше его не будим и не ждём от него заходов."""
    _СТОРОЖА.pop(code, None)


def сторожей() -> int:
    """Сколько сторожей слушает просьбы в этом процессе."""
    return len(_СТОРОЖА)


def попросить() -> int:
    """Разбудить всех сторожей. Возвращает, скольких удалось попросить.

    Ноль означает «в этом процессе сторожей нет» — это не «опрос не нужен»,
    и страница должна сказать именно так [NEWS-001].
    """
    global ПРОСИЛИ

    for событие in _СТОРОЖА.values():
        событие.set()
    if _СТОРОЖА:
        ПРОСИЛИ = time.time()
    return len(_СТОРОЖА)


def у_двери(code: str, стоим: bool) -> None:
    """Отметка «сторож сейчас у двери» — для строки состояния."""
    if стоим:
        _В_ДВЕРЯХ.add(code)
    else:
        _В_ДВЕРЯХ.discard(code)


def заход(code: str, *, код: int, найдено: int, новых: int, ошибка: str = "") -> None:
    """Запомнить итог захода. Это наблюдение, а не отчёт издания [NEWS-008]."""
    ЖУРНАЛ[code] = {
        "когда": time.time(), "код": int(код), "найдено": int(найдено),
        "новых": int(новых), "ошибка": str(ошибка or ""),
    }


def проверить(user_id: int) -> None:
    """Просьба прислать проверочное сообщение в бот."""
    ТЕСТЫ.append(int(user_id))


def состояние() -> dict[str, Any]:
    """Строка состояния: кто в дверях, когда был последний заход, что с ботом."""
    последний = max((шаг["когда"] for шаг in ЖУРНАЛ.values()), default=None)
    return {
        "сторожей": len(_СТОРОЖА),
        "в_дверях": sorted(_В_ДВЕРЯХ),
        "последний_заход": последний,
        "заходов": len(ЖУРНАЛ),
        "работаем_секунд": time.time() - НАЧАЛО,
        "просили": ПРОСИЛИ,
        "проверка": dict(ПРОВЕРКА),
    }


def забыть() -> None:
    """Очистка для тестов: общий стол не должен течь между проверками."""
    global ПРОСИЛИ

    _СТОРОЖА.clear()
    ЖУРНАЛ.clear()
    _В_ДВЕРЯХ.clear()
    ТЕСТЫ.clear()
    ПРОВЕРКА.clear()
    ПРОСИЛИ = None


async def loop(bot: Any, conn: Any, stop: Any, пауза: float = 1.0) -> int:
    """Контур проверок связи: отправляет то, что заказали со страницы.

    Отдельная задача, а не отправка прямо из веба: веб не ходит в сеть, иначе
    медленный Telegram задержит ответ страницы [NEWS-002].
    """
    отправлено = 0
    while not stop.is_set():
        while ТЕСТЫ:
            user_id = ТЕСТЫ.pop(0)
            # Номер в `users.id` — это и есть чат Telegram: личка человека.
            try:
                await bot.send(int(user_id), "Проверка связи: центр управления на месте.")
                ПРОВЕРКА.update({"когда": time.time(), "ответ": "доставлено"})
                отправлено += 1
            except Exception as exc:  # noqa: BLE001 — проверка не роняет сбор [CORE-017]
                ПРОВЕРКА.update({"когда": time.time(), "ответ": "не вышло: {}".format(exc)})
        try:
            await asyncio.wait_for(stop.wait(), timeout=пауза)
        except asyncio.TimeoutError:
            continue
    return отправлено


__all__ = ("ЖУРНАЛ", "ПРОВЕРКА", "ТЕСТЫ", "заход", "забыть", "loop", "отписаться",
           "подписаться", "попросить", "проверить", "состояние", "сторожей", "у_двери")
