"""Личная область видимости: что один человек имеет право видеть.

Зачем это отдельным модулем. Аккаунт в системе — это не только «кто вошёл»,
но и «что его»: подписки, темы, сторожа. Страницы ленты, поиска, правок и
всплесков строились, когда в системе был один хозяин, и показывали весь
архив. С приглашениями и личными выборами это стало чужой информацией:
человек, подписанный на «Медузу», не должен видеть материалы изданий,
которых не выбирал, и то, что попало в чужие темы [CORE-016].

Правило одно, и оно же обещание читателю: **человек видит материал, если
он из издания, на которое он подписан (или подписан на все), либо этот
материал ему уже приходил** — темой, сторожем, подпиской. Владелец видит
всё: он и есть тот, кто распоряжается сбором.

Модуль нарочно не импортирует соседей: его берут и `store`, и страницы, и
поиск, и замена `access.владелец` на прямую проверку роли — плата за
отсутствие цикла импортов. Роль лежит в той же строке `users`, и дублировать
одно сравнение дешевле, чем распутывать зависимости.

Пустая область видимости — не ошибка, а начало: новичку достаточно
подсказки со ссылкой на «Мои издания», а не пустого экрана без объяснений.
"""

from __future__ import annotations

from typing import Any

# Роль владельца. Строка — та же, что в `access.ВЛАДЕЛЕЦ`; копия здесь,
# чтобы модуль не тянул за собой `access` (см. docstring модуля).
ВЛАДЕЛЕЦ = "владелец"


def _роль(conn: Any, user_id: int) -> str:
    row = conn.execute("SELECT role FROM users WHERE id = ?",
                       (int(user_id or 0),)).fetchone()
    return str(row["role"] or "") if row is not None else ""


def видит_всё(conn: Any, user_id: int) -> bool:
    """Владелец ли. Ему область видимости не ограничиваем."""
    return _роль(conn, user_id) == ВЛАДЕЛЕЦ


def условие(conn: Any, user_id: int, alias: str = "i") -> tuple[str, list[Any]]:
    """SQL-хвост для личной области видимости. Владельцу — пусто, без фильтра.

    Возвращает пару (условие, параметры). Пустое условие — ограничений нет:
    его удобно склеивать в общий `WHERE`, не выясняя каждый раз, чей это
    запрос. Подписка с пустым кодом — «все издания», она снимает ограничение
    по источникам целиком. Ноль — служебная выборка: сторожа, внутренние
    шаги и тесты механики не персональны, и ограничивать их чужими
    подписками нельзя.
    """
    if user_id <= 0 or видит_всё(conn, user_id):
        return "", []
    sql = (
        "(EXISTS (SELECT 1 FROM feed_subs f WHERE f.user_id = ? AND f.code = '') "
        "OR {a}.source IN (SELECT f.code FROM feed_subs f "
        "WHERE f.user_id = ? AND f.code != '') "
        "OR {a}.id IN (SELECT d.item_id FROM deliveries d WHERE d.user_id = ?))"
    ).format(a=alias)
    return sql, [int(user_id), int(user_id), int(user_id)]


def пустая(conn: Any, user_id: int) -> bool:
    """Ни подписок, ни доставок. Владельцу пустой области не бывает.

    Это не «плохой человек», а человек, который ещё ничего не выбрал: страница
    ленты отвечает подсказкой, а не молчанием.
    """
    if видит_всё(conn, user_id):
        return False
    row = conn.execute(
        "SELECT (SELECT COUNT(*) FROM feed_subs WHERE user_id = ?) + "
        "(SELECT COUNT(*) FROM deliveries WHERE user_id = ?) AS всего",
        (int(user_id), int(user_id)),
    ).fetchone()
    return int(row["всего"] or 0) == 0


def видит(conn: Any, user_id: int, item_id: Any) -> bool:
    """Виден ли человеку один материал. Проверка для страниц по номеру.

    Страница «/материал?id=…» отвечала любому вошедшему: номер легко
    подставить руками, и это был бы обход всей области видимости через
    адресную строку [CORE-016].
    """
    try:
        номер = int(item_id)
    except (TypeError, ValueError):
        return False
    if номер <= 0:
        return False
    хвост, параметры = условие(conn, user_id)
    if not хвост:
        row = conn.execute("SELECT 1 FROM items WHERE id = ?", (номер,)).fetchone()
        return row is not None
    row = conn.execute(
        "SELECT 1 FROM items i WHERE i.id = ? AND {}".format(хвост),
        [номер, *параметры],
    ).fetchone()
    return row is not None


def тему_можно(conn: Any, user_id: int, topic_id: int) -> bool:
    """Своя ли тема. Чужие слова не должны просачиваться через поиск
    и ленту: адрес «?тема=N» — тоже вход, и он обязан проверить хозяина.

    Владельцу чужая тема тоже не видна: темы — личное, и роль не даёт
    права читать чужие слова. Управлять он может сбором и доступами, а не
    чужими интересами.
    """
    if topic_id <= 0:
        return False
    row = conn.execute(
        "SELECT 1 FROM topics WHERE id = ? AND user_id = ? AND enabled = 1",
        (int(topic_id), int(user_id)),
    ).fetchone()
    return row is not None


